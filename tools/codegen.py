#!/usr/bin/env python3
# The code generator (plan.md, section 2: MIPS -> C; phase 3): C for the functions and blocks tools/analyze.py finds, one C function per guest function, entered at any
# of its blocks. Each instruction is the runtime's own (runtime/cpu_ops.h: the interpreter's definitions), called with its word and address as constants, so the C
# compiler keeps only what that instruction does: the delay slots, the load in flight and the cycles are the interpreter's. A function goes from block to block by
# itself, and returns to the dispatcher (runtime/native.h) for a call, a return, a jump to another function or through a register it cannot follow, an exception,
# and, at the end of a block, a device event, an interrupt or an exit that is due. A block whose delay slot holds a branch stops before it, for the interpreter. Each
# function lists the guest code it was made from, which the runtime compares with memory before running it. The C goes to a build folder, never into the repository
# (plan.md, decision log). Usage: python3 tools/codegen.py <file.exe|disc.cue> --name <set> -o <file.c> [--profile profiles/<serial>/game.toml]
import argparse, re, sys
from pathlib import Path

import analyze, exe, mips


def runs(fn):   # the function's guest code: its blocks' addresses as runs of [start, end)
    out = []
    for s, e in sorted((b.start, b.end) for b in fn.blocks.values()):
        if out and s <= out[-1][1]: out[-1][1] = max(out[-1][1], e)
        else: out.append([s, e])
    return out


def block(b, word):   # the C of one block
    ops = [mips.decode(word(a)) for a in range(b.start, b.end, 4)]
    cut = len(ops) >= 2 and ops[-1].delay_slot and ops[-2].delay_slot   # a branch in a delay slot: the interpreter runs it, after the branch before it
    out = [f'b{b.start:08x}:']
    for i, op in enumerate(ops[:-1] if cut else ops):
        a = b.start + 4 * i
        out.append(f'    NATIVE_OP({"cop" if op.name in mips.COP else op.name}, 0x{a:08x}u, 0x{op.word:08x}u);   // {op.text(a)}')
    if not cut and b.exit == 'fall': out.append(f'    goto b{b.succs[0]:08x};')
    elif not cut and b.exit in ('branch', 'jump', 'switch') and b.succs:
        out.append('    if (NATIVE_GO) switch (m->cpu.pc) { ' + ' '.join(f'case 0x{s:08x}u: goto b{s:08x};' for s in dict.fromkeys(b.succs)) + ' }')
        out.append('    return;')
    else: out.append('    return;')
    return out


def generate(word, program, name):   # the C source of a native code set named `name` for the functions of an analyzed program
    if not re.fullmatch(r'[A-Za-z_]\w*', name): raise SystemExit(f'codegen: {name} is not a C name')
    fns = list(program.functions.values())
    out = [f'// Generated by tools/codegen.py: native code for {len(fns)} functions ({name}). Not to be edited or committed (plan.md, decision log)',
           '#include "native.h"', '']
    for f in fns:
        out += [f'static void f{f.start:08x}(ps1 *m) {{', '    switch (m->cpu.pc) {']
        out += [f'    case 0x{s:08x}u: goto b{s:08x};' for s in f.blocks]
        out += ['    default: return;', '    }']
        for b in f.blocks.values(): out += block(b, word)
        out += ['}']
        rs = runs(f)
        out.append(f'static const uint32_t r{f.start:08x}[][2] = {{' + ', '.join(f'{{0x{s:08x}u, 0x{e:08x}u}}' for s, e in rs) + '};')
        words = [word(a) for s, e in rs for a in range(s, e, 4)]
        out.append(f'static const uint32_t w{f.start:08x}[] = {{' + ', '.join(f'0x{w:08x}u' for w in words) + '};')
        out.append('')
    out.append('static const ps1_native_fn fns[] = {')
    out += [f'    {{f{f.start:08x}, 0x{f.start:08x}u, r{f.start:08x}, {len(runs(f))}, w{f.start:08x}}},' for f in fns]
    out.append('};')
    entries = sorted((s, i) for i, f in enumerate(fns) for s in f.blocks)
    out.append('static const ps1_native_entry entries[] = {')
    out += [f'    {{0x{s:08x}u, {i}}},' for s, i in entries]
    out += ['};', f'const ps1_native_set native_{name} = {{"{name}", fns, {len(fns)}, entries, {len(entries)}}};', '']
    return '\n'.join(out)


def main():
    p = argparse.ArgumentParser(description='Generate native C code for a PS-X EXE, or for the executable a disc boots')
    p.add_argument('path'); p.add_argument('--name', required=True, help='the C name of the code set: native_<name>')
    p.add_argument('-o', '--out', required=True, help='the C file to write, in a build folder'); p.add_argument('--profile', help="a game's profile, for its [analysis] hints")
    a = p.parse_args()
    x = exe.load(a.path)
    prog = analyze.analyze(x.word, [x.pc], analyze.hints_from_profile(a.profile) if a.profile else None)
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(generate(x.word, prog, a.name))
    print(f'codegen: {len(prog.functions)} functions, {sum(len(f.blocks) for f in prog.functions.values())} blocks into {a.out}; {len(prog.notes)} notes')
    return 0


if __name__ == '__main__': sys.exit(main())
