#!/usr/bin/env python3
# The code generator (plan.md, section 2: MIPS -> C; phase 3): C for the functions and blocks tools/analyze.py finds, one C function per guest function, entered at any
# of its blocks. Each instruction is the runtime's own (runtime/cpu_ops.h: the interpreter's definitions), called with its word and address as constants, so the C
# compiler keeps only what that instruction does: the delay slots, the load in flight and the cycles are the interpreter's. A function goes from block to block by
# itself, and returns to the dispatcher (runtime/native.h) for a call, a return, a jump to another function or through a register it cannot follow, an exception,
# and, at the end of a block, a device event, an interrupt or an exit that is due. A block whose delay slot holds a branch stops before it, for the interpreter. Each
# function lists the guest code it was made from, which the runtime compares with memory before running it. The C goes to a build folder, never into the repository
# (plan.md, decision log). Usage: python3 tools/codegen.py <file.exe|disc.cue> --name <set> -o <file.c> [--profile profiles/<serial>/game.toml]
import argparse, re, sys
from pathlib import Path

import analyze, exe, mips, overlays


def runs(fn):   # the function's guest code: its blocks' addresses as runs of [start, end)
    out = []
    for s, e in sorted((b.start, b.end) for b in fn.blocks.values()):
        if out and s <= out[-1][1]: out[-1][1] = max(out[-1][1], e)
        else: out.append([s, e])
    return out


def block(b, word):   # the C of one block
    ops = [mips.decode(word(a)) for a in range(b.start, b.end, 4)]
    cut = len(ops) >= 2 and ops[-1].delay_slot and ops[-2].delay_slot   # a branch in a delay slot: the interpreter runs it, after the branch before it
    out = [f'b{b.start:08x}:']
    for i, op in enumerate(ops[:-1] if cut else ops):
        a = b.start + 4 * i
        out.append(f'    NATIVE_OP({"cop" if op.name in mips.COP else op.name}, 0x{a:08x}u, 0x{op.word:08x}u);   // {op.text(a)}')
    if not cut and b.exit == 'fall': out.append(f'    goto b{b.succs[0]:08x};')
    elif not cut and b.exit in ('branch', 'jump', 'switch') and b.succs:
        out.append('    if (NATIVE_GO) switch (m->cpu.pc) { ' + ' '.join(f'case 0x{s:08x}u: goto b{s:08x};' for s in dict.fromkeys(b.succs)) + ' }')
        out.append('    return;')
    else: out.append('    return;')
    return out


def parts(word, program, name, split):   # the C of a native code set named `name`: the head, each function's lines and instruction count, and the tables
    if not re.fullmatch(r'[A-Za-z_]\w*', name): raise SystemExit(f'codegen: {name} is not a C name')
    images = [(f, getattr(f, 'image', None)) for f in program.functions.values()]
    fns = [f for f, _ in images]
    keys = {id(f): f'{f.start:08x}' + (f'_{b.digest}' if b else '') for f, b in images}
    sym = (lambda kind, f: f'{name}_{kind}{keys[id(f)]}') if split else (lambda kind, f: f'{kind}{keys[id(f)]}')
    st = '' if split else 'static '
    head = [f'// Generated by tools/codegen.py: native code for {len(fns)} functions ({name}). Not to be edited or committed (plan.md, decision log)',
            '#include "native.h"', '']
    bodies, sizes = [], []
    for f, image in images:
        fnword = image.word if image else word
        out = [f'{st}void {sym("f", f)}(ps1 *m) {{', '    switch (m->cpu.pc) {']
        out += [f'    case 0x{s:08x}u: goto b{s:08x};' for s in f.blocks]
        out += ['    default: return;', '    }']
        for b in f.blocks.values(): out += block(b, fnword)
        out += ['}']
        rs = runs(f)
        out.append(f'{st}const uint32_t {sym("r", f)}[][2] = {{' + ', '.join(f'{{0x{s:08x}u, 0x{e:08x}u}}' for s, e in rs) + '};')
        words = [fnword(a) for s, e in rs for a in range(s, e, 4)]
        out.append(f'{st}const uint32_t {sym("w", f)}[] = {{' + ', '.join(f'0x{w:08x}u' for w in words) + '};')
        out.append('')
        bodies.append(out); sizes.append(sum((b.end - b.start) // 4 for b in f.blocks.values()))
    table = ['static const ps1_native_fn fns[] = {']
    table += [f'    {{{sym("f", f)}, 0x{f.start:08x}u, {sym("r", f)}, {len(runs(f))}, {sym("w", f)}}},' for f in fns]
    table.append('};')
    entries = sorted((s, i) for i, f in enumerate(fns) for s in f.blocks)
    table.append('static const ps1_native_entry entries[] = {')
    table += [f'    {{0x{s:08x}u, {i}}},' for s, i in entries]
    table += ['};', f'const ps1_native_set native_{name} = {{"{name}", fns, {len(fns)}, entries, {len(entries)}}};', '']
    decls = [f'void {sym("f", f)}(ps1 *m); extern const uint32_t {sym("r", f)}[][2], {sym("w", f)}[];' for f in fns]
    return head, bodies, sizes, decls + [''] + table if split else table


def generate(word, program, name):   # the C of a native code set named `name`, in one source
    head, bodies, _, table = parts(word, program, name, False)
    return '\n'.join(head + [line for b in bodies for line in b] + table)


def generate_split(word, program, name, max_ops):   # the same in sources of functions, each closed once it holds max_ops instructions, and a last one of tables
    head, bodies, sizes, table = parts(word, program, name, True)
    files, part, n = [], [], 0
    for b, k in zip(bodies, sizes):
        part += b; n += k
        if n >= max_ops: files.append(part); part, n = [], 0
    if part: files.append(part)
    return ['\n'.join(head + p) for p in files] + ['\n'.join(head + table)]


RAM, ROM, ROM_BASE = 2 << 20, 512 << 10, 0x1fc00000


def memory(ram=None, rom=None, exe=None):   # word(address) as the CPU reads code: RAM through its mirrors (the first 8 MB), the BIOS ROM, or an executable's code
    def word(a):
        if a & 3: return None
        p = a & 0x1fffffff if a >> 29 in (4, 5) else a   # KSEG0 and KSEG1 drop their top bits; KUSEG is physical (runtime/mem.c, ps1_phys)
        if ram is not None and p < 0x800000: return int.from_bytes(ram[p % RAM:p % RAM + 4], 'little')
        if rom is not None and ROM_BASE <= p < ROM_BASE + ROM: return int.from_bytes(rom[p - ROM_BASE:p - ROM_BASE + 4], 'little')
        return exe.word(a) if exe else None
    return word


def load(path, bios=False, capture=None):   # (word, entry points) of an executable, a disc that boots one, or a BIOS ROM; a capture adds RAM and where code went
    ram = Path(f'{capture}.ram').read_bytes() if capture else None
    if ram is not None and len(ram) != RAM: raise SystemExit(f'codegen: {capture}.ram is not 2 MB of RAM')
    if bios:
        rom = Path(path).read_bytes()
        if len(rom) != ROM: raise SystemExit(f'codegen: {path} is not a 512 KB BIOS image')
        word, entries = memory(ram, rom), [0xbfc00000]
    else:
        x = exe.load(path)
        word, entries = memory(ram, None, x), [x.pc]
    if capture: entries += [a for a in (int(s, 16) for s in Path(f'{capture}.txt').read_text().split()) if word(a) is not None]
    return word, entries


def main():
    p = argparse.ArgumentParser(description='Generate native C code for a PS-X EXE, the executable a disc boots, or a BIOS ROM')
    p.add_argument('path'); p.add_argument('--name', required=True, help='the C name of the code set: native_<name>')
    p.add_argument('-o', '--out', required=True, help='the C file to write, in a build folder'); p.add_argument('--profile', help="a game's profile, for its [analysis] hints")
    p.add_argument('--bios', action='store_true', help='path is a 512 KB BIOS ROM, entered at its reset vector')
    p.add_argument('--capture', help='what tools/capture.c wrote: <capture>.ram, .txt, and optional .blocks (all observed code versions)')
    p.add_argument('--max-ops', type=int, default=0, help='split the C into files of functions with about this many instructions each, beside the tables in -o')
    a = p.parse_args()
    word, entries = load(a.path, a.bios, a.capture)
    prog = analyze.analyze(word, entries, analyze.hints_from_profile(a.profile) if a.profile else None)
    captured = Path(f'{a.capture}.blocks') if a.capture else None
    if captured and captured.exists():
        try: overlays.extend(prog, overlays.read(captured))
        except ValueError as e: raise SystemExit(f'codegen: {e}') from e
    out = Path(a.out); out.parent.mkdir(parents=True, exist_ok=True)
    for old in out.parent.glob(f'{out.stem}_*{out.suffix}'): old.unlink()   # the parts of an earlier run
    c = generate_split(word, prog, a.name, a.max_ops) if a.max_ops > 0 else [generate(word, prog, a.name)]
    files = [out.with_name(f'{out.stem}_{i + 1}{out.suffix}') for i in range(len(c) - 1)] + [out]
    for f, text in zip(files, c): f.write_text(text)
    print(f'codegen: {len(prog.functions)} functions, {sum(len(f.blocks) for f in prog.functions.values())} blocks into {a.out}'
          f'{f" and {len(files) - 1} more files" if len(files) > 1 else ""}; {len(prog.notes)} notes')
    return 0


if __name__ == '__main__': sys.exit(main())
